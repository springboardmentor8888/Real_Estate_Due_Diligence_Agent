// Export Helper Getters
export const getPropertyById = (id) => {
  if (!id) return MASTER_MOCK_PROPERTIES[0];
  const cleanId = id.toString().replace(/\D/g, "");
  const numeric = parseInt(cleanId, 10);

  let liveProps = [];
  try {
    const saved = localStorage.getItem("live_properties_store");
    if (saved) liveProps = JSON.parse(saved);
  } catch (e) { }

  const allProps = [...liveProps, ...MASTER_MOCK_PROPERTIES];
  return (
    allProps.find(
      (p) => p.numericId === numeric || p.propertyId === numeric || p.id === id || p.apnNumber === id
    ) || MASTER_MOCK_PROPERTIES[0]
  );
};

